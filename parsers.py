class JudgeParseError(ValueError):
    """The judge reply carries no verdict.

    Raised only by the corrected parsers. The shipped parsers never raise:
    silently converting an absent verdict into a verdict is defects 2 and 4 of
    issue #50, and reproducing that silence faithfully is the point of
    parse_shipped.
    """


