def verify_prompt_fidelity(pinned_source_path: str = "classifier_pinned_23dbdf6.py") -> dict:
    """Re-derive the prompts from the pinned source by AST and assert byte
    equality with the constants above. Raises AssertionError on any drift."""
    import ast
    import hashlib

    tree = ast.parse(open(pinned_source_path, encoding="utf-8").read())
    got = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name in (
            "Llama3JailbreakJudge",
            "Llama3RefusalJudge",
        ):
            for st in node.body:
                if isinstance(st, ast.Assign) and isinstance(st.value, ast.Constant):
                    got[(node.name, st.targets[0].id)] = st.value.value

    checks = {
        "JUDGE_PROMPT": (JUDGE_PROMPT, got[("Llama3JailbreakJudge", "USER_PROMPT")]),
        "POSITIVE_ANSWER": (POSITIVE_ANSWER, got[("Llama3JailbreakJudge", "POSITIVE_ANSWER")]),
        "REFUSAL_PROMPT": (REFUSAL_PROMPT, got[("Llama3RefusalJudge", "USER_PROMPT")]),
        "REFUSAL_POSITIVE_ANSWER": (
            REFUSAL_POSITIVE_ANSWER,
            got[("Llama3RefusalJudge", "POSITIVE_ANSWER")],
        ),
    }
    out = {}
    for name, (mine, theirs) in checks.items():
        assert mine == theirs, f"{name} drifted from pinned source"
        out[name] = hashlib.sha256(mine.encode()).hexdigest()
    return out


